using System.Text.RegularExpressions;
using FlcDataset.Core;

namespace FlcDataset.Extraction;

/// <summary>Accepted file plus its decoded document. Skipped files have <see cref="Document"/> == null.</summary>
public sealed record DiscoveredFile(DiscoveryRecord Record, SourceDocument? Document);

/// <summary>
/// Streams repository files in ordinal path order and applies include/exclude, size, encoding, generated, vendored,
/// license, secret and exact-duplicate rules. Every decision is reason-coded in the <see cref="DiscoveryRecord"/>.
/// </summary>
public sealed class Discoverer
{
    readonly DatasetConfig _config;
    readonly RepositoryInfo _repo;
    readonly Glob[] _include, _exclude, _generated, _vendored, _tests;
    readonly Regex[] _secrets;
    readonly Dictionary<string, string?> _projectByDir = new(StringComparer.Ordinal);
    readonly Dictionary<string, string> _firstPathBySha = new(StringComparer.Ordinal);

    static readonly Regex GeneratedMarker = new(
        @"<auto-?generated|This code was generated by a tool|\[(System\.CodeDom\.Compiler\.)?GeneratedCode(Attribute)?\(",
        RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

    public Discoverer(DatasetConfig config, RepositoryInfo repo)
    {
        _config = config;
        _repo = repo;
        var d = config.Discovery;
        _include = d.Include.Select(p => new Glob(p)).ToArray();
        _exclude = d.Exclude.Select(p => new Glob(p)).ToArray();
        _generated = d.GeneratedPatterns.Select(p => new Glob(p)).ToArray();
        _vendored = d.VendoredPatterns.Select(p => new Glob(p)).ToArray();
        _tests = d.TestPatterns.Select(p => new Glob(p)).ToArray();
        _secrets = config.Secrets.Patterns.Select(p => new Regex(p, RegexOptions.CultureInvariant)).ToArray();
    }

    public IReadOnlyList<Regex> SecretPatterns => _secrets;

    /// <summary>All candidate paths (relative, '/'-separated, ordinal order) matching an include pattern.</summary>
    public IEnumerable<string> EnumerateCandidatePaths()
    {
        var root = _repo.Root;
        var all = new List<string>();
        var stack = new Stack<string>();
        stack.Push(root);
        while (stack.Count > 0)
        {
            var dir = stack.Pop();
            foreach (var sub in Directory.EnumerateDirectories(dir))
            {
                var name = Path.GetFileName(sub);
                if (name == ".git") continue;
                var attr = File.GetAttributes(sub);
                if ((attr & FileAttributes.ReparsePoint) != 0) continue; // never follow symlinks out of the checkout
                stack.Push(sub);
            }
            foreach (var f in Directory.EnumerateFiles(dir))
            {
                var rel = Path.GetRelativePath(root, f).Replace('\\', '/');
                if (Glob.FirstMatch(_include, rel) is not null) all.Add(rel);
            }
        }
        all.Sort(StringComparer.Ordinal);
        return all;
    }

    public IEnumerable<DiscoveredFile> Discover()
    {
        foreach (var rel in EnumerateCandidatePaths())
            yield return Classify(rel);
    }

    DiscoveredFile Skip(string rel, string reason, long bytes = 0, string? pattern = null, string? sha = null, string? dupOf = null,
        bool generated = false, string? generatedReason = null) =>
        new(new DiscoveryRecord
        {
            RelativePath = rel, Status = "skipped", SkipReason = reason, MatchedPattern = pattern, Bytes = bytes, Sha256 = sha,
            Project = ProjectOf(rel), IsTest = IsTest(rel), DuplicateOf = dupOf, IsGenerated = generated, GeneratedReason = generatedReason,
        }, null);

    DiscoveredFile Classify(string rel)
    {
        var d = _config.Discovery;
        if (Glob.FirstMatch(_exclude, rel) is { } ex) return Skip(rel, "excluded_path", pattern: ex);
        var full = Path.Combine(_repo.Root, rel);
        var size = new FileInfo(full).Length;
        if (size > d.MaxFileBytes) return Skip(rel, "too_large", size);
        if (Glob.FirstMatch(_vendored, rel) is { } vp) return Skip(rel, "vendored_path", size, vp);
        if (Glob.FirstMatch(_generated, rel) is { } gp) return Skip(rel, "generated_path", size, gp, generated: true, generatedReason: "path:" + gp);

        var bytes = File.ReadAllBytes(full);
        var doc = SourceDocument.TryDecode(bytes, out var decodeError);
        if (doc is null) return Skip(rel, decodeError!, size);
        if (string.IsNullOrWhiteSpace(doc.Text)) return Skip(rel, "empty", size, sha: doc.Sha256);

        // Content-based generated detection: inspect the leading region only (header comments / first declarations).
        var head = doc.Text.Length > 4000 ? doc.Text[..4000] : doc.Text;
        if (GeneratedMarker.Match(head) is { Success: true } gm)
            return Skip(rel, "generated_marker", size, sha: doc.Sha256, generated: true, generatedReason: "marker:" + gm.Value);
        if (doc.Lines.Any(l => l.End - l.Start > d.MaxFileLineChars)) return Skip(rel, "long_lines", size, sha: doc.Sha256);
        if (!_repo.License.Allowed && !_config.License.AllowUnknown)
            return Skip(rel, "license_not_allowed", size, sha: doc.Sha256);
        foreach (var rx in _secrets)
            if (rx.Match(doc.Text) is { Success: true }) return Skip(rel, "secret_detected", size, rx.ToString(), doc.Sha256);
        if (_firstPathBySha.TryGetValue(doc.Sha256, out var first)) return Skip(rel, "exact_duplicate", size, sha: doc.Sha256, dupOf: first);
        _firstPathBySha[doc.Sha256] = rel;

        var (split, group) = SplitOf(rel);
        return new DiscoveredFile(new DiscoveryRecord
        {
            RelativePath = rel, Status = "accepted", Bytes = size, Sha256 = doc.Sha256, Project = ProjectOf(rel), IsTest = IsTest(rel),
            Split = split, Lines = doc.Lines.Count, Chars = doc.Text.Length,
        }, doc);
    }

    public bool IsTest(string rel) => Glob.FirstMatch(_tests, rel) is not null;

    /// <summary>Nearest ancestor directory containing a *.csproj (relative path of that project), or null.</summary>
    public string? ProjectOf(string rel)
    {
        var dir = Path.GetDirectoryName(rel)?.Replace('\\', '/') ?? "";
        var visited = new List<string>();
        string? result = null;
        while (true)
        {
            if (_projectByDir.TryGetValue(dir, out var cached)) { result = cached; break; }
            visited.Add(dir);
            var abs = Path.Combine(_repo.Root, dir);
            var proj = Directory.Exists(abs) ? Directory.EnumerateFiles(abs, "*.csproj").Order(StringComparer.Ordinal).FirstOrDefault() : null;
            if (proj is not null) { result = Path.GetRelativePath(_repo.Root, proj).Replace('\\', '/'); break; }
            if (dir.Length == 0) break;
            dir = Path.GetDirectoryName(dir)?.Replace('\\', '/') ?? "";
        }
        foreach (var v in visited) _projectByDir[v] = result;
        return result;
    }

    /// <summary>Split assignment by group (project or file) before any caret expansion; deterministic from seed + group key.</summary>
    public (string Split, string Group) SplitOf(string rel)
    {
        var s = _config.Split;
        var project = ProjectOf(rel);
        var group = s.GroupBy switch
        {
            "file" => rel,
            "project" => project ?? rel,
            _ => project is null ? "(no-project):" + rel
                : Regex.Match(Path.GetFileNameWithoutExtension(project), s.FamilyPattern) is { Success: true, Groups.Count: > 1 } m && m.Groups[1].Success
                    ? m.Groups[1].Value : project,
        };
        if (s.Overrides.TryGetValue(group, out var forced)) return (forced, group);
        var u = Hashing.Uniform(_config.Seed.ToString(), "split", _repo.RepositoryId, group);
        var split = u < s.EvalFraction ? "eval" : u < s.EvalFraction + s.TestFraction ? "test" : "train";
        return (split, group);
    }
}
